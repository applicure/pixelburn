#!/usr/bin/env python3
"""Writes services/src/card/glyphs.generated.ts: glyph outlines for the share card.

The card is rendered on the API server, whose image has no system fonts. Drawing text as outlines means the
result does not depend on fontconfig, and buyer text never reaches an SVG parser as text.

Fonts (SIL OFL 1.1, the same families as the site), from https://github.com/google/fonts/tree/main/ofl:
  python3 -m venv venv && venv/bin/pip install fonttools uharfbuzz
  venv/bin/python services/scripts/build-card-glyphs.py <dir with the three variable .ttf files>
"""
import json
import sys
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

OUT = Path(__file__).resolve().parents[1] / "src/card/glyphs.generated.ts"
ASCII = "".join(chr(c) for c in range(0x20, 0x7F))
LATIN = ASCII + "".join(chr(c) for c in range(0xA1, 0x180) if c != 0xAD) + "–—‘’“”•…€™"
FONTS = {
    "display": ("Anybody", {"wght": 900, "wdth": 125}, ASCII + "×·…–"),
    "text": ("SchibstedGrotesk", {"wght": 700}, LATIN),
    "mono": ("MartianMono", {"wght": 500, "wdth": 87.5}, ASCII + "×·"),
}
KERN_CHARS = {"display": ASCII, "text": ASCII, "mono": ""}


def build(path, axes, chars, kern_chars, tmp):
    font = instantiateVariableFont(TTFont(path), axes)
    font.save(tmp)
    upm = font["head"].unitsPerEm
    cmap, glyphset, hmtx = font.getBestCmap(), font.getGlyphSet(), font["hmtx"]
    glyphs = {}
    for ch in chars:
        name = cmap.get(ord(ch))
        if name is None:
            continue
        pen = SVGPathPen(glyphset, ntos=lambda v: str(round(v)))
        glyphset[name].draw(TransformPen(pen, (1, 0, 0, -1, 0, 0)))  # y down, as SVG
        glyphs[ch] = [hmtx[name][0], pen.getCommands()]

    blob = hb.Blob.from_file_path(str(tmp))
    hbfont = hb.Font(hb.Face(blob))
    def advance(text):
        buf = hb.Buffer()
        buf.add_str(text)
        buf.guess_segment_properties()
        hb.shape(hbfont, buf, {"liga": False})
        return sum(p.x_advance for p in buf.glyph_positions)
    single = {c: advance(c) for c in kern_chars if c in glyphs}
    kern = {}
    for a in single:
        for b in single:
            d = advance(a + b) - single[a] - single[b]
            if d:
                kern[a + b] = d
    return {"upm": upm, "capHeight": font["OS/2"].sCapHeight, "glyphs": glyphs, "kern": kern}


def main():
    src = Path(sys.argv[1])
    tmp = Path("/tmp/card-glyphs-instance.ttf") if len(sys.argv) < 3 else Path(sys.argv[2])
    out = {}
    for key, (prefix, axes, chars) in FONTS.items():
        path = next(p for p in src.glob("*.ttf") if p.name.startswith(prefix))
        out[key] = build(path, axes, chars, KERN_CHARS[key], tmp)
    OUT.write_text(
        "// Generated by services/scripts/build-card-glyphs.py. Do not edit by hand.\n"
        "// Outlines from Anybody, Schibsted Grotesk and Martian Mono, under the SIL Open Font License 1.1.\n"
        "export interface GlyphFont {\n  upm: number;\n  capHeight: number;\n"
        "  /** char -> [advance, SVG path with y pointing down] in font units */\n"
        "  glyphs: Record<string, [number, string]>;\n  /** char pair -> kerning in font units */\n  kern: Record<string, number>;\n}\n"
        f"export const GLYPHS: Record<\"display\" | \"text\" | \"mono\", GlyphFont> = {json.dumps(out, ensure_ascii=True, separators=(',', ':'))};\n"
    )
    print(OUT, OUT.stat().st_size, {k: (len(v["glyphs"]), len(v["kern"])) for k, v in out.items()})


if __name__ == "__main__":
    main()
