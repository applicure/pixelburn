// Builds ../DEVNET.md from ../devnet-log.json + derived addresses (pubkeys only; never secrets or RPC URLs).
import { Keypair, PublicKey } from "@solana/web3.js";
import { PROGRAM_ID, configPda, canvasPda, buybackVaultPda, auctionPda, auctionAdPda, pythPriceFeedAccount } from "@mpb/sdk";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const here = dirname(fileURLToPath(import.meta.url));
const pk = (n: string) => Keypair.fromSecretKey(Uint8Array.from(JSON.parse(readFileSync(resolve(here, `../keys/${n}.json`), "utf8")))).publicKey.toBase58();
const ex = (a: string) => `[\`${a}\`](https://explorer.solana.com/address/${a}?cluster=devnet)`;
const log: { step: string; explorer: string; sig: string; at: string; [k: string]: unknown }[] = existsSync(resolve(here, "../devnet-log.json"))
  ? JSON.parse(readFileSync(resolve(here, "../devnet-log.json"), "utf8")) : [];
const mint = process.env.MINT ?? "", curve = process.env.CURVE ?? "";
const pdaProgData = PublicKey.findProgramAddressSync([PROGRAM_ID.toBuffer()], new PublicKey("BPFLoaderUpgradeab1e11111111111111111111111"))[0].toBase58();
const rows = [
  ["program `pixel`", PROGRAM_ID.toBase58()], ["programdata", pdaProgData], ["config PDA", configPda().toBase58()], ["canvas PDA", canvasPda().toBase58()],
  ["buyback vault PDA", buybackVaultPda().toBase58()], ["auction PDA (not created)", auctionPda().toBase58()], ["auction ad PDA (not created)", auctionAdPda().toBase58()],
  ["token mint (PXTEST, Token-2022, pump.fun)", mint], ["pump bonding curve", curve], ["Pyth SOL/USD (sponsored)", pythPriceFeedAccount().toBase58()],
  ["deployer", pk("deployer")], ["admin (upgrade authority)", pk("admin")], ["keeper", pk("keeper")], ["treasury", pk("treasury")], ["test buyer", pk("buyer")],
];
const md = `# Devnet deployment (The Million Pixel Burn: \`pixel\`)

Devnet only. Test token **"Pixel Burn DEVNET TEST" (PXTEST)**, no value. Keys live in \`chain/keys/\` (gitignored); only pubkeys appear here.
Generated by \`chain/scripts/devnet-report.ts\` from \`chain/devnet-log.json\`.

## Addresses
| what | address |
|---|---|
${rows.map(([k, v]) => `| ${k} | ${v ? ex(v) : "-"} |`).join("\n")}

## Transactions
| # | step | time (UTC) | tx | notes |
|---|---|---|---|---|
${log.map((l, i) => {
  const { step, sig, explorer, at, ...rest } = l;
  const notes = Object.entries(rest).map(([k, v]) => `${k}: ${typeof v === "object" ? JSON.stringify(v) : v}`).join("; ").replace(/\|/g, "/").slice(0, 400);
  return `| ${i + 1} | ${step} | ${at.slice(0, 19).replace("T", " ")} | [${sig.slice(0, 10)}…](${explorer}) | ${notes} |`;
}).join("\n")}
`;
writeFileSync(resolve(here, "../DEVNET.md"), md);
console.log("wrote DEVNET.md with", log.length, "txs");
